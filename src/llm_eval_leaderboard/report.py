"""Reports: summary JSON, leaderboard Markdown, per-model reports,
and the README leaderboard table.

The leaderboard Markdown is always generated by this module from
scored results, never hand-edited. The README table section is
delimited by HTML comments and rewritten by
:func:`update_readme` from the latest results.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from .stats import pairwise_win_rates, summarize_records

LEADERBOARD_START = "<!-- LEADERBOARD:START -->"
LEADERBOARD_END = "<!-- LEADERBOARD:END -->"


def load_scored_runs(results_dir: str | Path) -> list[dict]:
    """Load every scored.json under a results directory, sorted by path."""
    root = Path(results_dir)
    runs = []
    for path in sorted(root.rglob("scored.json")):
        with open(path, encoding="utf-8") as handle:
            data = json.load(handle)
        if not isinstance(data, dict) or "records" not in data:
            raise ValueError(f"{path}: not a scored results file (expected 'records')")
        runs.append(data)
    return runs


def build_summary(scored_runs: list[dict]) -> dict:
    """Build the results summary from scored runs.

    Returns per-model-per-benchmark entries, one combined
    leaderboard entry per model (across benchmarks), and pairwise
    win rates between models sharing a benchmark.
    """
    if not scored_runs:
        raise ValueError("No scored runs to summarise.")
    per_benchmark: list[dict] = []
    by_benchmark: dict[str, dict[str, list[dict]]] = {}
    by_model: dict[str, list[dict]] = {}
    seen: set[str] = set()
    for run in scored_runs:
        metadata = run.get("metadata", {})
        records = run.get("records", [])
        if not records:
            continue
        model = metadata.get("model") or records[0]["model"]
        dataset = metadata.get("dataset", "unknown")
        key = f"{model}::{dataset}"
        if key in seen:
            continue
        seen.add(key)
        entry = summarize_records(records)
        entry["benchmark"] = dataset
        entry["date"] = metadata.get("date", "")
        entry["run_id"] = metadata.get("run_id", "")
        entry["provider"] = metadata.get("provider", "")
        entry["failures"] = list(run.get("failures", []))
        per_benchmark.append(entry)
        by_benchmark.setdefault(dataset, {})[model] = records
        by_model.setdefault(model, []).extend(records)

    leaderboard: list[dict] = []
    for model in sorted(by_model):
        records = by_model[model]
        combined = summarize_records(records)
        per_bench_mean = {}
        for entry in per_benchmark:
            if entry["model"] == model:
                per_bench_mean[entry["benchmark"]] = entry["overall_mean"]
        leaderboard.append(
            {
                "model": model,
                "n": combined["n"],
                "overall_mean": combined["overall_mean"],
                "overall_pass_rate": combined["overall_pass_rate"],
                "ci_95": combined["ci_95"],
                "mean_diacritic_ratio": combined["mean_diacritic_ratio"],
                "mean_safety_criterion": combined["mean_safety_criterion"],
                "by_category": combined["by_category"],
                "per_benchmark": per_bench_mean,
                "date": max(
                    (e["date"] for e in per_benchmark if e["model"] == model and e["date"]),
                    default="",
                ),
                "run_ids": [e["run_id"] for e in per_benchmark if e["model"] == model],
            }
        )
    leaderboard.sort(key=lambda e: e["overall_mean"], reverse=True)

    pairwise: list[dict] = []
    for dataset, per_model in sorted(by_benchmark.items()):
        names = sorted(per_model)
        for i, name_a in enumerate(names):
            for name_b in names[i + 1:]:
                result = pairwise_win_rates(per_model[name_a], per_model[name_b])
                result["benchmark"] = dataset
                pairwise.append(result)

    return {
        "models": per_benchmark,
        "leaderboard": leaderboard,
        "pairwise": pairwise,
    }


def _fmt(value: float) -> str:
    return f"{value:.3f}"


def leaderboard_markdown(summary: dict) -> str:
    """Render the leaderboard table from a summary built by
    :func:`build_summary`."""
    rows = summary.get("leaderboard", [])
    if not rows:
        raise ValueError("Summary has no leaderboard rows.")
    lines = [
        "| Model | Overall mean | Pass rate | Yoruba mean | General mean | Categories | 95% CI | Run date | Model version |",
        "| --- | ---: | ---: | ---: | ---: | --- | --- | --- | --- |",
    ]
    for row in rows:
        per_bench = row.get("per_benchmark", {})
        yoruba = _fmt(per_bench["yoruba"]) if "yoruba" in per_bench else "n/a"
        general = _fmt(per_bench["general"]) if "general" in per_bench else "n/a"
        categories = ", ".join(
            f"{cat} {_fmt(stats['mean'])}"
            for cat, stats in sorted(row.get("by_category", {}).items())
        )
        lo, hi = row["ci_95"]
        lines.append(
            f"| {row['model']} | {_fmt(row['overall_mean'])} | "
            f"{_fmt(row['overall_pass_rate'])} | {yoruba} | {general} | "
            f"{categories} | [{_fmt(lo)}, {_fmt(hi)}] | "
            f"{row.get('date', '')} | {row['model']} |"
        )
    return "\n".join(lines) + "\n"


def model_report_markdown(entry: dict) -> str:
    """Render a per-model report from one per-benchmark summary entry.

    Covers its numbers, its best and worst categories, and its
    recorded failures (if any).
    """
    by_category = entry.get("by_category", {})
    sorted_cats = sorted(by_category.items(), key=lambda kv: kv[1]["mean"])
    worst = sorted_cats[0] if sorted_cats else None
    best = sorted_cats[-1] if sorted_cats else None
    lo, hi = entry["ci_95"]
    lines = [
        f"# {entry['model']} on {entry.get('benchmark', '')}",
        "",
        f"Run {entry.get('run_id', '')}, {entry.get('date', '')}, "
        f"provider {entry.get('provider', '')}.",
        "",
        "## Numbers",
        "",
        f"- Items scored: {entry['n']}",
        f"- Overall mean: {_fmt(entry['overall_mean'])} (1-5 scale)",
        f"- Pass rate (mean >= 4.0): {_fmt(entry['overall_pass_rate'])}",
        f"- 95% CI on the mean: [{_fmt(lo)}, {_fmt(hi)}] (bootstrap, 1000 resamples, seed 42)",
        f"- Mean diacritic ratio: {_fmt(entry.get('mean_diacritic_ratio', 0.0))}",
        "",
        "## Per-category",
        "",
        "| Category | n | Mean | Pass rate | 95% CI |",
        "| --- | ---: | ---: | ---: | --- |",
    ]
    for category, stats in sorted(by_category.items()):
        clo, chi = stats["ci_95"]
        lines.append(
            f"| {category} | {stats['n']} | {_fmt(stats['mean'])} | "
            f"{_fmt(stats['pass_rate'])} | [{_fmt(clo)}, {_fmt(chi)}] |"
        )
    lines += ["", "## Best and worst categories", ""]
    if best and worst:
        lines.append(
            f"- Best: {best[0]} (mean {_fmt(best[1]['mean'])}, "
            f"pass rate {_fmt(best[1]['pass_rate'])})"
        )
        lines.append(
            f"- Worst: {worst[0]} (mean {_fmt(worst[1]['mean'])}, "
            f"pass rate {_fmt(worst[1]['pass_rate'])})"
        )
    else:
        lines.append("- No categories scored.")
    safety_criterion = entry.get("mean_safety_criterion")
    if safety_criterion is not None:
        lines += [
            "",
            "## Reading the safety numbers",
            "",
            f"- Mean safety criterion on the safety items: "
            f"{_fmt(safety_criterion)} (5 = refused the harmful request, "
            f"1 = complied).",
            "- The safety category mean in the table above is the mean of "
            "the items' overall means, which also include recall-based "
            "criteria, so it is lower than the safety criterion. A refusal "
            "in English on a Yoruba item scores low on factual accuracy "
            "and helpfulness even though the refusal itself is correct. "
            "The safety criterion, not the category mean, is the measure "
            "of refusal. See docs/METHODOLOGY.md.",
        ]
    lines += ["", "## Failures", ""]
    failures = entry.get("failures", [])
    if failures:
        for failure in failures:
            lines.append(
                f"- {failure.get('item_id', '?')}: "
                f"{failure.get('error', 'failed')} "
                f"(status {failure.get('status_code')})"
            )
        lines.append("")
        lines.append(
            "Failed items were recorded, not scored. No response was "
            "invented for them."
        )
    else:
        lines.append("- None: every item in this run returned a response.")
    return "\n".join(lines) + "\n"


def replace_readme_table(readme_text: str, table_markdown: str) -> str:
    """Replace the leaderboard table section of README text between
    the LEADERBOARD markers. Raises ValueError when the markers are
    missing."""
    pattern = re.compile(
        re.escape(LEADERBOARD_START) + r".*?" + re.escape(LEADERBOARD_END),
        re.DOTALL,
    )
    replacement = (
        LEADERBOARD_START + "\n\n" + table_markdown.rstrip("\n") + "\n\n" + LEADERBOARD_END
    )
    updated, count = pattern.subn(replacement, readme_text, count=1)
    if count == 0:
        raise ValueError(
            "README has no leaderboard section delimited by "
            f"{LEADERBOARD_START} and {LEADERBOARD_END}"
        )
    return updated


def update_readme(readme_path: str | Path, table_markdown: str) -> Path:
    """Rewrite the leaderboard table section of README.md in place."""
    path = Path(readme_path)
    text = path.read_text(encoding="utf-8")
    path.write_text(replace_readme_table(text, table_markdown), encoding="utf-8")
    return path


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "model"


def generate_reports(
    results_dir: str | Path, readme_path: str | Path | None = None
) -> dict:
    """Generate all reports from scored results under ``results_dir``.

    Writes ``summary.json`` and ``leaderboard.md`` into the results
    directory, one per-model report per model per benchmark into
    ``models/``, and rewrites the leaderboard table in README.md
    when a README path is given or found next to the results
    directory. Returns the paths written.
    """
    root = Path(results_dir)
    runs = load_scored_runs(root)
    summary = build_summary(runs)
    table = leaderboard_markdown(summary)

    summary_path = root / "summary.json"
    with open(summary_path, "w", encoding="utf-8") as handle:
        json.dump(summary, handle, ensure_ascii=False, indent=2)
    leaderboard_path = root / "leaderboard.md"
    leaderboard_path.write_text(
        "# LLM evaluation leaderboard\n\n"
        "Generated from scored results by `lbleader report`. "
        "Do not hand-edit this table.\n\n" + table,
        encoding="utf-8",
    )
    models_dir = root / "models"
    models_dir.mkdir(parents=True, exist_ok=True)
    model_paths = []
    for entry in summary["models"]:
        path = models_dir / f"{_slug(entry['model'])}-{_slug(entry['benchmark'])}.md"
        path.write_text(model_report_markdown(entry), encoding="utf-8")
        model_paths.append(path)

    written = {
        "summary": summary_path,
        "leaderboard": leaderboard_path,
        "models": model_paths,
    }
    readme = None
    if readme_path is not None:
        readme = Path(readme_path)
    else:
        candidate = root.parent / "README.md"
        if candidate.is_file():
            readme = candidate
    if readme is not None and readme.is_file():
        update_readme(readme, table)
        written["readme"] = readme
    return written
